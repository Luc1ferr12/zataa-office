// → { w, h, on(x, y) } ; teks diubah ke huruf besar, karakter asing jadi spasi
export function textBitmap(str, scale = 1) {
  const s = String(str).toUpperCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
  const w = Math.max(1, s.length * 4 - 1), h = 5;
  const bits = new Uint8Array(w * h);
  [...s].forEach((ch, i) => {
    const g = G[ch] ?? G[' '];
    for (let k = 0; k < 15; k++) if (g[k] === '1') bits[(Math.floor(k / 3)) * w + i * 4 + (k % 3)] = 1;
  });
  return { w: w * scale, h: h * scale, on: (x, y) => x >= 0 && y >= 0 && x < w * scale && y < h * scale && bits[Math.floor(y / scale) * w + Math.floor(x / scale)] === 1 };
}
